package com.pharadev.receiptscanner.presentation.ui.manual

import android.net.Uri
import androidx.lifecycle.LiveData
import androidx.lifecycle.MutableLiveData
import androidx.lifecycle.ViewModel
import androidx.lifecycle.viewModelScope
import com.pharadev.receiptscanner.domain.model.CategoryDomain
import com.pharadev.receiptscanner.domain.model.ReceiptDomain
import com.pharadev.receiptscanner.domain.repository.CategoryRepository
import com.pharadev.receiptscanner.domain.repository.ReceiptRepository
import dagger.hilt.android.lifecycle.HiltViewModel
import kotlinx.coroutines.launch
import java.math.BigDecimal
import java.time.LocalDate
import java.time.LocalDateTime
import java.util.*
import javax.inject.Inject

@HiltViewModel
class ManualEntryViewModel @Inject constructor(
    private val receiptRepository: ReceiptRepository,
    private val categoryRepository: CategoryRepository
) : ViewModel() {
    
    private val _categories = MutableLiveData<List<CategoryDomain>>()
    val categories: LiveData<List<CategoryDomain>> = _categories
    
    private val _saveState = MutableLiveData<SaveState>(SaveState.Idle)
    val saveState: LiveData<SaveState> = _saveState
    
    sealed class SaveState {
        object Idle : SaveState()
        object Loading : SaveState()
        object Success : SaveState()
        data class Error(val message: String) : SaveState()
    }
    
    suspend fun loadCategories() {
        try {
            categoryRepository.getAllCategories().collect { categoryList ->
                _categories.value = categoryList
            }
        } catch (exception: Exception) {
            _categories.value = emptyList()
        }
    }
    
    suspend fun saveReceipt(
        imageUri: Uri?,
        vendor: String,
        amount: BigDecimal,
        date: Date,
        categoryId: Long,
        notes: String?
    ) {
        _saveState.value = SaveState.Loading
        
        try {
            // Find the category
            val category = _categories.value?.find { it.id == categoryId }
                ?: return // Category not found
            
            // Convert Date to LocalDate
            val calendar = Calendar.getInstance()
            calendar.time = date
            val localDate = LocalDate.of(
                calendar.get(Calendar.YEAR),
                calendar.get(Calendar.MONTH) + 1,
                calendar.get(Calendar.DAY_OF_MONTH)
            )
            
            val now = LocalDateTime.now()
            
            val receipt = ReceiptDomain(
                id = 0L, // Will be generated by repository
                imagePath = imageUri?.toString() ?: "",
                vendor = vendor,
                amount = amount,
                date = localDate,
                category = category,
                notes = notes,
                createdAt = now,
                modifiedAt = now
            )
            
            receiptRepository.insertReceipt(receipt)
            _saveState.value = SaveState.Success
            
        } catch (exception: Exception) {
            _saveState.value = SaveState.Error(
                exception.message ?: "Failed to save receipt"
            )
        }
    }
    
    fun resetSaveState() {
        _saveState.value = SaveState.Idle
    }
}